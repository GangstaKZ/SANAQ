export function LanguageProvider({ children }) {
  const [lang, setLang] = useLocalStorage("sanaq-language", "ru");
  return (
    <Context.Provider
      value={{
        lang,
        setLang,
        t: (text) => (lang === "kk" ? kk[text] || text : text),
      }}
    >
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
